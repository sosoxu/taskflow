// Escape a string for safe inclusion in a YAML double-quoted scalar.
// We use double-quoted scalars and escape backslash and double-quote.
std::string yamlDoubleQuote(const std::string& s) {
    std::string out;
    out.reserve(s.size() + 2);
    for (char c : s) {
        if (c == '\\') {
            out += "\\\\";
        } else if (c == '"') {
            out += "\\\"";
        } else if (static_cast<unsigned char>(c) < 0x20) {
            // control chars -> escape as needed (rare in config values)
            out += "\\x";
            char hex[3];
            std::snprintf(hex, sizeof(hex), "%02x", static_cast<unsigned char>(c));
            out += hex;
        } else {
            out += c;
        }
    }
    return "\"" + out + "\"";
}

// Escape a string so it can be safely embedded inside single quotes in a
// POSIX shell command. Each single quote becomes '\'' (close quote, escaped
// quote, reopen quote).
std::string shellSingleQuote(const std::string& s) {
    std::string out;
    out.reserve(s.size() + 2);
    for (char c : s) {
        if (c == '\'') {
            out += "'\\''";
        } else {
            out += c;
        }
    }
    return "'" + out + "'";
}

